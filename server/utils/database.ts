import bcrypt from 'bcryptjs'
import { createError, type H3Event } from 'h3'
import { Pool } from 'pg'

let pool: Pool | undefined
let initialization: Promise<void> | undefined

async function initializeDatabase(database: Pool, event: H3Event): Promise<void> {
  const config = useRuntimeConfig(event)
  const client = await database.connect()

  try {
    await client.query('BEGIN')
    await client.query(`
      CREATE TABLE IF NOT EXISTS app_users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username VARCHAR(40) NOT NULL UNIQUE,
        display_name VARCHAR(100) NOT NULL,
        password_hash TEXT NOT NULL,
        role VARCHAR(16) NOT NULL CHECK (role IN ('admin', 'employee')),
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `)
    await client.query(`
      CREATE TABLE IF NOT EXISTS app_sessions (
        token_hash CHAR(64) PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
        expires_at TIMESTAMPTZ NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `)
    await client.query(`
      CREATE INDEX IF NOT EXISTS app_sessions_expires_at_idx
      ON app_sessions (expires_at)
    `)

    const username = config.bootstrapAdminUsername.trim().toLowerCase()
    const existingAdmin = await client.query<{ role: string }>(
      'SELECT role FROM app_users WHERE username = $1',
      [username]
    )

    if (existingAdmin.rows[0]) {
      if (existingAdmin.rows[0].role !== 'admin') {
        throw createError({
          statusCode: 409,
          statusMessage: 'El usuario configurado para el administrador ya pertenece a otra cuenta.'
        })
      }
    } else {
      const password = config.bootstrapAdminPassword
      const displayName = config.bootstrapAdminName.trim()

      if (!password || !displayName) {
        throw createError({
          statusCode: 503,
          statusMessage: 'Configura NUXT_BOOTSTRAP_ADMIN_PASSWORD antes de crear el administrador inicial.'
        })
      }

      if (Buffer.byteLength(password, 'utf8') > 72) {
        throw createError({
          statusCode: 503,
          statusMessage: 'La contraseña inicial no puede superar 72 bytes.'
        })
      }

      const passwordHash = await bcrypt.hash(password, 12)
      await client.query(
        `INSERT INTO app_users (username, display_name, password_hash, role)
         VALUES ($1, $2, $3, 'admin')
         ON CONFLICT (username) DO NOTHING`,
        [username, displayName, passwordHash]
      )
    }

    await client.query('COMMIT')
  } catch (error) {
    await client.query('ROLLBACK')
    throw error
  } finally {
    client.release()
  }
}

export async function getDatabase(event: H3Event): Promise<Pool> {
  const config = useRuntimeConfig(event)

  if (!config.databaseUrl) {
    throw createError({
      statusCode: 503,
      statusMessage: 'Conecta PostgreSQL y configura NUXT_DATABASE_URL en Railway para activar el acceso.'
    })
  }

  if (!pool) {
    pool = new Pool({
      connectionString: config.databaseUrl,
      connectionTimeoutMillis: 10_000,
      idleTimeoutMillis: 30_000,
      max: 5
    })
  }

  if (!initialization) {
    initialization = initializeDatabase(pool, event).catch((error: unknown) => {
      initialization = undefined
      throw error
    })
  }

  await initialization
  return pool
}
